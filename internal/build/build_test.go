// crossBuild builds helloMain for another OS and returns the first bytes of the binary.
func crossBuild(t *testing.T, opts Options) (string, []byte) {
	t.Helper()
	if testing.Short() {
		t.Skip("builds a Go program; skipped with -short")
	}
	if _, err := LookGo(); err != nil {
		t.Skip(err)
	}
	dir := t.TempDir()
	if err := Prepare(dir, []codegen.File{helloMain}); err != nil {
		t.Fatal(err)
	}
	opts.Output = filepath.Join(dir, "dist", "hello")
	bin, err := Build(context.Background(), dir, opts)
	if err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(bin)
	if err != nil {
		t.Fatal(err)
	}
	if len(b) < 4 {
		t.Fatalf("%s is only %d bytes", bin, len(b))
	}
	return bin, b[:4]
}

func TestBuildCrossCompileLinux(t *testing.T) {
	t.Parallel()
	bin, magic := crossBuild(t, Options{OS: "linux", Arch: "amd64", Release: true})
	if filepath.Base(bin) != "hello" {
		t.Errorf("binary = %s, want hello with no .exe", bin)
	}
	if string(magic) != "\x7fELF" {
		t.Errorf("binary starts %q, want an ELF header", magic)
	}
}

func TestBuildWindowsTargetAddsExe(t *testing.T) {
	t.Parallel()
	bin, magic := crossBuild(t, Options{OS: "windows", Arch: "amd64"})
	if filepath.Base(bin) != "hello.exe" {
		t.Errorf("binary = %s, want hello.exe", bin)
	}
	if string(magic[:2]) != "MZ" {
		t.Errorf("binary starts %q, want a PE header", magic)
	}
}
