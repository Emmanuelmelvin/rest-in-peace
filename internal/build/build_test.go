// TestBuildLinksRuntime proves the riskiest piece of the pipeline works end to end:
// embedded runtime → build directory → go build → a native binary that runs.
func TestBuildLinksRuntime(t *testing.T) {
	if testing.Short() {
		t.Skip("builds a Go program; skipped with -short")
	}
	if _, err := LookGo(); err != nil {
		t.Skip(err)
	}
	dir := t.TempDir()
	main := codegen.File{Name: "main.go", Src: []byte(`// Code generated by hand for a test.
package main

import "ripapp/rt"

func main() {
	rt.Print(rt.MapOf("message", "HELLO WORLD"))
}
`)}
	if err := Prepare(dir, []codegen.File{main}); err != nil {
		t.Fatal(err)
	}
	bin, err := Build(context.Background(), dir, Options{Output: filepath.Join(dir, "bin", "hello")})
	if err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command(bin).Output()
	if err != nil {
		t.Fatal(err)
	}
	if got, want := strings.TrimSpace(string(out)), `{"message":"HELLO WORLD"}`; got != want {
		t.Fatalf("got %s, want %s", got, want)
	}
}

// helloMain is a minimal generated program that links the runtime.
var helloMain = codegen.File{Name: "main.go", Src: []byte(`// Code generated by hand for a test.
package main

import "ripapp/rt"

func main() { rt.Print("HELLO") }
`)}

func TestPrepareRemovesStaleGoFiles(t *testing.T) {
	dir := t.TempDir()
	write := func(rel, content string) {
		t.Helper()
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("m_deleted.go", "package main\n")
	write(filepath.Join("rt", "removed_from_runtime.go"), "package rt\n")
	write("go.sum", "kept\n")
	write("notes.txt", "kept\n")

	if err := Prepare(dir, []codegen.File{helloMain, {Name: "m_billing.go", Src: []byte("package main\n")}}); err != nil {
		t.Fatal(err)
	}
	for _, gone := range []string{"m_deleted.go", filepath.Join("rt", "removed_from_runtime.go")} {
		if _, err := os.Stat(filepath.Join(dir, gone)); !errors.Is(err, fs.ErrNotExist) {
			t.Errorf("%s should have been removed (stat err: %v)", gone, err)
		}
	}
	for _, kept := range []string{"go.sum", "notes.txt", "main.go", "m_billing.go", "go.mod"} {
		if _, err := os.Stat(filepath.Join(dir, kept)); err != nil {
			t.Errorf("%s should exist: %v", kept, err)
		}
	}

	// A second Prepare drops generated files that are no longer produced.
	if err := Prepare(dir, []codegen.File{helloMain}); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(dir, "m_billing.go")); !errors.Is(err, fs.ErrNotExist) {
		t.Errorf("m_billing.go should have been removed by the second Prepare (stat err: %v)", err)
	}
}

func TestPrepareCopiesRuntimeWithoutTests(t *testing.T) {
	dir := t.TempDir()
	if err := Prepare(dir, nil); err != nil {
		t.Fatal(err)
	}
	want, err := fs.Glob(rip.RuntimeFS, "rt/*.go")
	if err != nil {
		t.Fatal(err)
	}
	var wantNames []string
	for _, p := range want {
		if !strings.HasSuffix(p, "_test.go") {
			wantNames = append(wantNames, path.Base(p))
		}
	}
	entries, err := os.ReadDir(filepath.Join(dir, "rt"))
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, e := range entries {
		got = append(got, e.Name())
	}
	if strings.Join(got, " ") != strings.Join(wantNames, " ") {
		t.Errorf("rt/ = %v, want %v", got, wantNames)
	}
	for _, name := range wantNames {
		embedded, _ := fs.ReadFile(rip.RuntimeFS, "rt/"+name)
		copied, err := os.ReadFile(filepath.Join(dir, "rt", name))
		if err != nil || !bytes.Equal(embedded, copied) {
			t.Errorf("rt/%s differs from the embedded copy (err: %v)", name, err)
		}
	}
}

func TestGoModContent(t *testing.T) {
	dir := t.TempDir()
	if err := Prepare(dir, nil); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	got := string(b)
	head := "module " + ModulePath + "\n\ngo " + GoVersion + "\n"
	if !strings.HasPrefix(got, head) {
		t.Fatalf("go.mod starts\n%s\nwant it to start\n%s", got, head)
	}
	imports, err := runtimeImports()
	if err != nil {
		t.Fatal(err)
	}
	if len(imports) == 0 && got != head {
		t.Errorf("rt imports no third-party packages, so go.mod should have no require block; got\n%s", got)
	}
}

// TestGoModPinsRuntimeImports checks that every module rt imports is pinned in
// the generated go.mod. If this fails after rt gains an import, add a blank
// import of that package to internal/build so the CLI links the module and its
// version appears in the build info.
func TestGoModPinsRuntimeImports(t *testing.T) {
	imports, err := runtimeImports()
	if err != nil {
		t.Fatal(err)
	}
	mod := string(goMod())
	for _, imp := range imports {
		pinned := false
		for _, r := range runtimeRequires() {
			if imp == r.Path || strings.HasPrefix(imp, r.Path+"/") {
				pinned = strings.Contains(mod, "\t"+r.Path+" "+r.Version+"\n")
			}
		}
		if !pinned {
			t.Errorf("rt imports %s, but go.mod does not pin its module:\n%s", imp, mod)
		}
	}
}

func TestBinaryPath(t *testing.T) {
	for _, tc := range []struct{ output, goos, want string }{
		{"dist/app", "windows", "dist/app.exe"},
		{"dist/app.exe", "windows", "dist/app.exe"},
		{"dist/APP.EXE", "windows", "dist/APP.EXE"},
		{"dist/app.v2", "windows", "dist/app.v2.exe"},
		{`dist\app`, "windows", `dist\app.exe`},
		{`dist\app.exe`, "windows", `dist\app.exe`},
		{"dist/app", "linux", "dist/app"},
		{"dist/app", "darwin", "dist/app"},
	} {
		if got := binaryPath(tc.output, tc.goos); got != tc.want {
			t.Errorf("binaryPath(%q, %q) = %q, want %q", tc.output, tc.goos, got, tc.want)
		}
	}
	want := "app"
	if runtime.GOOS == "windows" {
		want = "app.exe"
	}
	if got := binaryPath("app", ""); got != want {
		t.Errorf("binaryPath(app, \"\") = %q, want %q on %s", got, want, runtime.GOOS)
	}
}

