package build

import (
	"context"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/Emmanuelmelvin/rest-in-peace/internal/compiler/codegen"
)

// TestBuildLinksRuntime proves the riskiest piece of the pipeline works end to end:
// embedded runtime → build directory → go build → a native binary that runs.
func TestBuildLinksRuntime(t *testing.T) {
	if testing.Short() {
		t.Skip("builds a Go program; skipped with -short")
	}
	if _, err := LookGo(); err != nil {
		t.Skip(err)
	}
	dir := t.TempDir()
	main := codegen.File{Name: "main.go", Src: []byte(`// Code generated by hand for a test.
package main

import "ripapp/rt"

func main() {
	rt.Print(rt.MapOf("message", "HELLO WORLD"))
}
`)}
	if err := Prepare(dir, []codegen.File{main}); err != nil {
		t.Fatal(err)
	}
	bin, err := Build(context.Background(), dir, Options{Output: filepath.Join(dir, "bin", "hello")})
	if err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command(bin).Output()
	if err != nil {
		t.Fatal(err)
	}
	if got, want := strings.TrimSpace(string(out)), `{"message":"HELLO WORLD"}`; got != want {
		t.Fatalf("got %s, want %s", got, want)
	}
}
