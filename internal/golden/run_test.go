// These tests prove the build-and-run half of the runner with hand-written Go
// programs, so it works before the compiler exists.

func buildAndRunMain(t *testing.T, src string, timeout time.Duration) (*Outcome, error) {
	t.Helper()
	if testing.Short() {
		t.Skip("builds a Go program; skipped with -short")
	}
	if _, err := build.LookGo(); err != nil {
		t.Skip(err)
	}
	files := []codegen.File{{Name: "main.go", Src: []byte(src)}}
	return BuildAndRun(context.Background(), t.TempDir(), files, timeout)
}

func TestBuildAndRunStdout(t *testing.T) {
	t.Parallel()
	o, err := buildAndRunMain(t, `// Code generated by hand for a test.
package main

import "ripapp/rt"

func main() {
	rt.Print("READY.")
	rt.Print(rt.Div(int64(5), int64(2)), " ", rt.MapOf("a", int64(1)))
}
`, runTimeout)
	if err != nil {
		t.Fatal(err)
	}
	if o.ExitCode != 0 {
		t.Fatalf("exit status %d; stderr:\n%s", o.ExitCode, o.Stderr)
	}
	if got, want := Normalize(o.Stdout), "READY.\n2.5 {\"a\":1}"; got != want {
		t.Fatalf("stdout = %q, want %q", got, want)
	}
}

// TestBuildAndRunRuntimeError mimics how a generated program reports an
// uncaught runtime error: the classic message on stderr and a non-zero exit.
func TestBuildAndRunRuntimeError(t *testing.T) {
	t.Parallel()
	o, err := buildAndRunMain(t, `// Code generated by hand for a test.
package main

import (
	"os"

	"ripapp/rt"
)

func main() {
	defer func() {
		if r := recover(); r != nil {
			e := r.(*rt.Error)
			e.File, e.Line = "boom.bas", 3
			os.Stderr.WriteString(e.Error() + "\r\n")
			os.Exit(1)
		}
	}()
	rt.Print("BEFORE")
	rt.Print(rt.Div(int64(1), int64(0)))
	rt.Print("AFTER")
}
`, runTimeout)
	if err != nil {
		t.Fatal(err)
	}
	if o.ExitCode != 1 {
		t.Errorf("exit status = %d, want 1", o.ExitCode)
	}
	if got := Normalize(o.Stdout); got != "BEFORE" {
		t.Errorf("stdout = %q, want BEFORE", got)
	}
	if err := MatchLines(o.Stderr, "?DIVISION BY ZERO ERROR IN boom.bas:3\n"); err != nil {
		t.Error(err)
	}
	if err := MatchLines(o.Stderr, "?DIVISION BY ZERO ERROR IN boom.bas:4"); err == nil {
		t.Error("a wrong line number matched")
	}
	if err := MatchLines(o.Stderr, "?DIVISION BY ZERO ERROR IN boom.bas:3 — some other hint"); err == nil {
		t.Error("a wrong hint matched")
	}
}

func TestBuildAndRunTimeout(t *testing.T) {
	t.Parallel()
	_, err := buildAndRunMain(t, `// Code generated by hand for a test.
package main

import (
	"time"

	"ripapp/rt"
)

func main() {
	rt.Print("WAITING")
	time.Sleep(time.Hour)
}
`, 500*time.Millisecond)
	if !errors.Is(err, ErrTimeout) {
		t.Fatalf("err = %v, want ErrTimeout", err)
	}
}

// TestBuildAndRunLineDirective verifies that //line directives survive
// build.Prepare and build.Build (including on Windows) so runtime.CallersFrames
// reports the BASIC file basename and line number (design §4.5).
func TestBuildAndRunLineDirective(t *testing.T) {
	t.Parallel()
	o, err := buildAndRunMain(t, `// Code generated by hand for a test.
package main

import (
	"os"
	"path"
	"runtime"
	"strings"

	"ripapp/rt"
)

func basicLocation() (string, int) {
	var pcs [16]uintptr
	n := runtime.Callers(2, pcs[:])
	frames := runtime.CallersFrames(pcs[:n])
	for {
		f, more := frames.Next()
		file := strings.ReplaceAll(f.File, "\\", "/")
		if strings.HasSuffix(file, ".bas") {
			return path.Base(file), f.Line
		}
		if !more {
			break
		}
	}
	return "", 0
}

func main() {
	defer func() {
		if r := recover(); r != nil {
			e := r.(*rt.Error)
			e.File, e.Line = basicLocation()
			os.Stderr.WriteString(e.Error() + "\n")
			os.Exit(1)
		}
	}()
//line billing.bas:42
	_ = rt.Get(nil, "total")
}
`, runTimeout)
	if err != nil {
		t.Fatal(err)
	}
	if o.ExitCode != 1 {
		t.Errorf("exit status = %d, want 1", o.ExitCode)
	}
	if err := MatchLines(o.Stderr, "?NIL ACCESS ERROR IN billing.bas:42"); err != nil {
		t.Error(err)
	}
}

func TestMatchLine(t *testing.T) {
	const full = "?SYNTAX ERROR IN x.bas:3 — expected THEN after IF condition"
	for _, tc := range []struct {
		got, want string
		ok        bool
	}{
		{full, "?SYNTAX ERROR IN x.bas:3", true},
		{full, full, true},
		{full, "?SYNTAX ERROR IN x.bas:3 — expected THEN", false},
		{full, "?SYNTAX ERROR IN x.bas:4", false},
		{full, "?SYNTAX ERROR IN x.bas", false},
		{full, "?TYPE MISMATCH ERROR IN x.bas:3", false},
		{"?SYNTAX ERROR IN x.bas:3", "?SYNTAX ERROR IN x.bas:3", true},
		{"?SYNTAX ERROR IN x.bas:3", full, false},
	} {
		if got := MatchLine(tc.got, tc.want); got != tc.ok {
			t.Errorf("MatchLine(%q, %q) = %v, want %v", tc.got, tc.want, got, tc.ok)
		}
	}
}

func TestMatchLines(t *testing.T) {
	got := "?SYNTAX ERROR IN a.bas:1 — one\r\n?SYNTAX ERROR IN a.bas:5 — two\r\n"
	if err := MatchLines(got, "?SYNTAX ERROR IN a.bas:1\n?SYNTAX ERROR IN a.bas:5\n\n"); err != nil {
		t.Error(err)
	}
	if err := MatchLines(got, "?SYNTAX ERROR IN a.bas:1"); err == nil {
		t.Error("a missing line matched")
	}
	if err := MatchLines("", ""); err != nil {
		t.Error(err)
	}
	if err := MatchLines(got, ""); err == nil {
		t.Error("unexpected output matched empty")
	}
}

func TestNormalize(t *testing.T) {
	if got := Normalize("a\r\nb\r\n\r\n"); got != "a\nb" {
		t.Errorf("Normalize = %q", got)
	}
}
