// fakeServer is a hand-written Go program that behaves like a compiled RIP
// server, so the HTTP mode is tested without the real one. RIP_FAKE_MODE
// picks how it misbehaves.
const fakeServer = `// Code generated by hand for a test.
package main

import (
	"encoding/json"
	"fmt"
	"io"
	"net"
	"net/http"
	"os"
	"sync/atomic"
	"time"
)

func writeJSON(w http.ResponseWriter, status int, body string) {
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.WriteHeader(status)
	io.WriteString(w, body+"\n")
}

func main() {
	port := os.Getenv("PORT")
	switch os.Getenv("RIP_FAKE_MODE") {
	case "notbuilt":
		fmt.Fprintln(os.Stderr, "?INTERNAL ERROR IN main.bas:2 — ROUTE … CALL is not built yet (task 2.1 in .kiro/specs/rip-basic/tasks.md)")
		os.Exit(1)
	case "crash":
		fmt.Println("BOOTING")
		fmt.Fprintln(os.Stderr, "?UNDEFINED ERROR IN main.bas:1 — environment variable DATABASE_URL is required")
		os.Exit(1)
	case "bindfail":
		fmt.Fprintln(os.Stderr, "listen tcp :"+port+": bind: address already in use")
		os.Exit(1)
	case "hang":
		fmt.Println("BOOTING")
		time.Sleep(time.Hour)
	}

	var ids atomic.Int64
	mux := http.NewServeMux()
	mux.HandleFunc("GET /hello", func(w http.ResponseWriter, r *http.Request) {
		writeJSON(w, 200, ` + "`" + `{"message":"HELLO WORLD"}` + "`" + `)
	})
	mux.HandleFunc("POST /echo", func(w http.ResponseWriter, r *http.Request) {
		b, _ := io.ReadAll(r.Body)
		if !json.Valid(b) {
			writeJSON(w, 400, ` + "`" + `{"error":"BODY IS NOT VALID JSON"}` + "`" + `)
			return
		}
		w.Header().Set("X-Echo-Content-Type", r.Header.Get("Content-Type"))
		w.Header().Set("X-Echo-Ghost", r.Header.Get("x-ghost"))
		writeJSON(w, 201, string(b))
	})
	mux.HandleFunc("GET /boom", func(w http.ResponseWriter, r *http.Request) {
		writeJSON(w, 500, fmt.Sprintf(` + "`" + `{"error":"INTERNAL ERROR","requestId":"req-%d"}` + "`" + `, ids.Add(1)))
	})
	mux.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		writeJSON(w, 404, ` + "`" + `{"error":"ROUTE NOT FOUND IN THIS REALM"}` + "`" + `)
	})

	l, err := net.Listen("tcp", "127.0.0.1:"+port)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println("BOOTING")
	fmt.Println("READY. listening on :" + port)
	http.Serve(l, mux)
}
`

// TestHTTPMode runs the HTTP mode end to end against fakeServer.
func TestHTTPMode(t *testing.T) {
	if testing.Short() {
		t.Skip("builds a Go program; skipped with -short")
	}
	if _, err := build.LookGo(); err != nil {
		t.Skip(err)
	}
	dir := t.TempDir()
	bin, err := BuildBinary(context.Background(), dir, []codegen.File{{Name: "main.go", Src: []byte(fakeServer)}})
	if err != nil {
		t.Fatal(err)
	}
	start := func(t *testing.T, mode string, timeout time.Duration) (*Server, error) {
		t.Setenv("RIP_FAKE_MODE", mode)
		s, err := StartServer(bin, dir, timeout)
		if err == nil {
			t.Cleanup(s.Stop)
		}
		return s, err
	}

	t.Run("passing script", func(t *testing.T) {
		s, err := start(t, "", readyTimeout)
		if err != nil {
			t.Fatal(err)
		}
		if stdout, _ := s.Output(); !strings.Contains(stdout, "READY. listening on :"+strconv.Itoa(s.Port)) {
			t.Errorf("PORT was not passed on; stdout:\n%s", stdout)
		}
		exs, err := ParseScript("pass.http", `
### hello
GET /hello
=> 200
content-type: application/json; charset=utf-8

{"message": "HELLO WORLD"}

### echo keeps key order, sends JSON by default, and passes headers on
POST /echo
X-Ghost: Casper

{"b": 1, "a": {"y": [1, 2.50], "x": null}}
=> 201
x-echo-content-type: application/json
x-echo-ghost: Casper

{"b": 1, "a": {"y": [1, 2.5], "x": null}}

### an explicit content type wins
POST /echo
Content-Type: application/vnd.ghost+json

{}
=> 201
x-echo-content-type: application/vnd.ghost+json

{}

### invalid JSON is sent as written
POST /echo

{"title":
=> 400

{"error": "BODY IS NOT VALID JSON"}

### wildcards
GET /boom
=> 500
content-type: <any>

{"error": "INTERNAL ERROR", "requestId": "<any string>"}

### not found
DELETE /nowhere?x=1
=> 404

{"error": "ROUTE NOT FOUND IN THIS REALM"}
`)
		if err != nil {
			t.Fatal(err)
		}
		for _, err := range RunScript(context.Background(), s.URL, exs) {
			t.Error(err)
		}
	})

	t.Run("mismatches are reported", func(t *testing.T) {
		s, err := start(t, "", readyTimeout)
		if err != nil {
			t.Fatal(err)
		}
		exs, err := ParseScript("fail.http", `
### wrong order
POST /echo
X-Ghost: Casper

{"b": 1, "a": 2}
=> 201

{"a": 2, "b": 1}

### this one passes
GET /hello
=> 200

{"message": "HELLO WORLD"}

### wrong status and header
GET /hello
=> 201
x-ghost: <any>

{"message": "HELLO WORLD"}
`)
		if err != nil {
			t.Fatal(err)
		}
		errs := RunScript(context.Background(), s.URL, exs)
		if len(errs) != 2 {
			t.Fatalf("got %d errors, want 2: %v", len(errs), errs)
		}
		for _, want := range []string{
			`line 3 (wrong order): body: $ has keys in order ["b" "a"], want ["a" "b"]`,
			"--- request\nPOST /echo\nX-Ghost: Casper\n\n{\"b\": 1, \"a\": 2}",
			"--- want\n=> 201\n\n{\"a\": 2, \"b\": 1}",
			"--- got\n=> 201\ncontent-length:",
			"x-echo-ghost: Casper\n\n{\"b\": 1, \"a\": 2}",
		} {
			if !strings.Contains(errs[0].Error(), want) {
				t.Errorf("first error doesn't contain %q:\n%v", want, errs[0])
			}
		}
		for _, want := range []string{
			"line 18 (wrong status and header): status is 200, want 201; header x-ghost is missing",
			"--- got\n=> 200\n",
		} {
			if !strings.Contains(errs[1].Error(), want) {
				t.Errorf("second error doesn't contain %q:\n%v", want, errs[1])
			}
		}
	})

	t.Run("stop leaves nothing running", func(t *testing.T) {
		s, err := start(t, "", readyTimeout)
		if err != nil {
			t.Fatal(err)
		}
		s.Stop()
		s.Stop() // a second Stop is harmless
		if exited, _ := s.Exited(); !exited {
			t.Fatal("process still running after Stop")
		}
		c, err := net.DialTimeout("tcp", "127.0.0.1:"+strconv.Itoa(s.Port), time.Second)
		if err == nil {
			c.Close()
			t.Error("port still accepts connections after Stop")
		}
	})

	t.Run("exits before ready", func(t *testing.T) {
		_, err := start(t, "crash", readyTimeout)
		var nr *NotReadyError
		if !errors.As(err, &nr) || !errors.Is(err, ErrNotReady) {
			t.Fatalf("err = %v, want a NotReadyError", err)
		}
		if !strings.Contains(nr.Reason, "exited") || Normalize(nr.Stdout) != "BOOTING" || !strings.Contains(nr.Stderr, "DATABASE_URL") {
			t.Errorf("NotReadyError = %+v", nr)
		}
		if strings.Contains(nr.Stderr, notBuiltMarker) {
			t.Error("a real crash looks like a missing feature")
		}
	})

	t.Run("runtime not built", func(t *testing.T) {
		_, err := start(t, "notbuilt", readyTimeout)
		var nr *NotReadyError
		if !errors.As(err, &nr) || !strings.Contains(nr.Stderr, notBuiltMarker) {
			t.Fatalf("err = %v, want a NotReadyError mentioning %q", err, notBuiltMarker)
		}
	})

	t.Run("never ready", func(t *testing.T) {
		begin := time.Now()
		_, err := start(t, "hang", 500*time.Millisecond)
		var nr *NotReadyError
		if !errors.As(err, &nr) || !strings.Contains(nr.Reason, "within 500ms") {
			t.Fatalf("err = %v, want a NotReadyError for the timeout", err)
		}
		if Normalize(nr.Stdout) != "BOOTING" {
			t.Errorf("stdout = %q, want BOOTING", nr.Stdout)
		}
		if d := time.Since(begin); d > 5*time.Second {
			t.Errorf("took %s to give up", d)
		}
	})

	t.Run("port taken", func(t *testing.T) {
		_, err := start(t, "bindfail", readyTimeout)
		if !errors.Is(err, errPortTaken) {
			t.Fatalf("err = %v, want errPortTaken after retrying", err)
		}
	})

	t.Run("server dies mid-script", func(t *testing.T) {
		s, err := start(t, "", readyTimeout)
		if err != nil {
			t.Fatal(err)
		}
		exs, err := ParseScript("dies.http", "###\nGET /hello\n=> 200\n\n<any>\n###\nGET /hello\n=> 200\n\n<any>\n")
		if err != nil {
			t.Fatal(err)
		}
		s.Stop()
		errs := RunScript(context.Background(), s.URL, exs)
		if len(errs) != 1 || !strings.Contains(errs[0].Error(), "--- error") {
			t.Fatalf("errs = %v, want one send error that stops the script", errs)
		}
	})
}
