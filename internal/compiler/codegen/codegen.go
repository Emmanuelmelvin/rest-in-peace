// Package codegen turns a checked program into Go source for package main
// (design §4). The output imports the runtime as "ripapp/rt".
//
// Layout of the output:
//
//	main.go       func main() { rt.Main(…) }, which runs each module's top-level code
//	m_<mod>.go    one file per .bas module: globals, functions, and the
//	              module's run function (structured) or its one classic
//	              function with a label per line (classic, design §4.7)
//
// Naming: BASIC names become b_<module>_<name> in lower case (design §4.3).
// Everything codegen invents itself starts with rip_, so it can never collide
// with a BASIC name.
package codegen

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"

	"github.com/Emmanuelmelvin/rest-in-peace/internal/compiler/ast"
	"github.com/Emmanuelmelvin/rest-in-peace/internal/compiler/diag"
	"github.com/Emmanuelmelvin/rest-in-peace/internal/compiler/token"
)

// RuntimeImport is the import path of the runtime inside a build directory.
const RuntimeImport = "ripapp/rt"

// Header starts every generated file.
const Header = "// Code generated by rip. DO NOT EDIT."

// Options control code generation.
type Options struct {
	// Guard inserts c.Guard() at loop back-edges and GOTOs (playground builds, design §4.12).
	Guard bool
}

// File is one generated Go file.
type File struct {
	Name string // e.g. "main.go", "m_billing.go"
	Src  []byte
}

// kindInternal marks a bug in codegen itself rather than in the BASIC program.
const kindInternal diag.Kind = "INTERNAL"

// Generate emits Go source for the program. If any diagnostic is an error, no
// files are returned.
func Generate(p *ast.Program, opts Options) ([]File, diag.List) {
	if p == nil || len(p.Files) == 0 {
		entry := ""
		if p != nil {
			entry = p.Entry
		}
		return nil, diag.List{diag.Errorf(token.Pos{File: entry, Line: 1, Col: 1}, kindInternal, "there is nothing to compile")}
	}
	var (
		ds    diag.List
		files []File
		runs  []string
		seen  = map[string]string{}
	)
	for _, f := range p.Files {
		g := newGen(p, f, opts)
		if other, dup := seen[g.mod]; dup {
			ds = append(ds, diag.Errorf(token.Pos{File: f.Name, Line: 1, Col: 1}, diag.Syntax,
				"%s and %s would both become module %q; rename one of them", other, f.Name, g.mod))
			continue
		}
		seen[g.mod] = f.Name
		src := g.generate()
		ds = append(ds, g.diags...)
		files = append(files, File{Name: goFileName(g.mod), Src: src})
		runs = append(runs, g.runName())
	}
	if ds.HasErrors() {
		return nil, ds
	}
	main, err := mainFile(runs)
	if err != nil {
		return nil, append(ds, diag.Errorf(token.Pos{File: p.Entry, Line: 1, Col: 1}, kindInternal, "%v", err))
	}
	return append([]File{main}, files...), ds
}

// mainFile runs each module's top-level statements, in order, inside rt.Main.
func mainFile(runs []string) (File, error) {
	var o out
	o.w(Header)
	o.w("")
	o.w("package main")
	o.w("")
	o.w("import ", strconv.Quote(RuntimeImport))
	o.w("")
	o.w("func main() {")
	o.w("rt.Main(func(c *rt.Ctx) {")
	for _, r := range runs {
		o.w(r, "(c)")
	}
	o.w("})")
	o.w("}")
	src, err := format.Source([]byte(o.String()))
	return File{Name: "main.go", Src: src}, err
}

// ---- Per-module generator ----

// gen generates one .bas file.
type gen struct {
	prog  *ast.Program
	file  *ast.File
	opts  Options
	mod   string // mangled module name
	diags diag.List

	funcs     map[string]*fnInfo // by canonical name
	funcOrder []*fnInfo
	globals   map[string]*varInfo
	globOrder []*varInfo

	tmp    int       // counter for rip_ temporaries and labels
	cur    token.Pos // the statement being compiled, for diagnostics
	cl     *classicState
	mods   *basImportState
	goImps *goImportState
}

// varInfo is a variable, parameter or constant.
type varInfo struct {
	name    string // canonical BASIC name
	goName  string
	t       typ
	decl    string // declared type name, e.g. "MAP"; "" if not declared
	konst   bool   // CONST: assigning it is an error
	goConst string // set when the CONST compiles to a Go const with this value
	param   bool
}

// fnInfo is a FUNCTION or SUB.
type fnInfo struct {
	decl       *ast.FuncDecl
	name       string
	goName     string
	params     []*varInfo
	result     typ
	resultDecl string
	isSub      bool
	locals     map[string]*varInfo
	localOrder []*varInfo
}

// scope is where an expression or statement is compiled.
type scope struct {
	fn    *fnInfo // nil for top-level code
	loops []*loop
	depth int // block nesting below the function or file body
}

// loop is an enclosing FOR, WHILE or DO, for EXIT.
type loop struct {
	kind  token.Kind
	label string // structured: the Go label to break; classic: the end label
	used  bool
}

func newGen(p *ast.Program, f *ast.File, opts Options) *gen {
	return &gen{
		prog:    p,
		file:    f,
		opts:    opts,
		mod:     moduleName(f.Name),
		funcs:   map[string]*fnInfo{},
		globals: map[string]*varInfo{},
		mods:    &basImportState{},
		goImps:  &goImportState{},
	}
}

func (g *gen) runName() string { return "rip_" + g.mod + "_run" }

// generate returns the formatted Go source of the module.
func (g *gen) generate() []byte {
	for _, im := range g.file.Imports {
		if im.FromGo {
			g.goImport(im)
		} else {
			g.basImport(im)
		}
	}
	var body out
	if g.file.Mode == token.Classic {
		g.classicFile(&body)
	} else {
		g.structuredFile(&body)
	}
	var o out
	o.w(Header)
	o.w("")
	o.w("package main")
	o.w("")
	extraImps := g.extraGoImports()
	if len(extraImps) == 0 {
		o.w("import ", strconv.Quote(RuntimeImport))
	} else {
		o.w("import (")
		o.w(strconv.Quote(RuntimeImport))
		for _, imp := range extraImps {
			o.w(imp)
		}
		o.w(")")
	}
	o.w("")
	o.raw(body.String())
	src := []byte(o.String())
	if g.diags.HasErrors() {
		return src
	}
	formatted, err := format.Source(src)
	if err != nil {
		g.errorf(token.Pos{Line: 1}, kindInternal, "generated Go does not parse (%v); this is a bug in rip's code generation", err)
		return src
	}
	return formatted
}

// ---- Diagnostics ----

// pos completes a diagnostic position. A node without a position (Line 0)
// gets the position of the statement being compiled.
func (g *gen) pos(p token.Pos) token.Pos {
	if p.Line < 1 {
		p = g.cur
	}
	if p.File == "" {
		p.File = g.file.Name
	}
	if p.Line < 1 {
		p.Line = 1
	}
	return p
}

func (g *gen) errorf(p token.Pos, kind diag.Kind, format string, args ...any) {
	g.diags = append(g.diags, diag.Errorf(g.pos(p), kind, format, args...))
}

func (g *gen) todo(p token.Pos, task, what string) {
	g.diags = append(g.diags, diag.Todo(g.pos(p), task, what))
}

// trial runs f and throws away any diagnostics it reported; ok says whether there were none.
func (g *gen) trial(f func() gexpr) (gexpr, bool) {
	n := len(g.diags)
	tmp := g.tmp
	e := f()
	ok := len(g.diags) == n
	g.diags = g.diags[:n]
	if !ok {
		g.tmp = tmp
	}
	return e, ok
}

// ---- Output ----

// out collects Go source lines. It never uses its input as a format string,
// because generated code contains user strings.
type out struct{ b strings.Builder }

func (o *out) w(parts ...string) {
	for _, p := range parts {
		o.b.WriteString(p)
	}
	o.b.WriteByte('\n')
}

func (o *out) raw(s string)     { o.b.WriteString(s) }
func (o *out) String() string   { return o.b.String() }
func (o *out) appendOut(x *out) { o.b.WriteString(x.String()) }

// dir writes the //line directive that maps the next Go line to a BASIC line
// (design §4.5). It must start at column 1.
func (g *gen) dir(o *out, p token.Pos) {
	p = g.pos(p)
	o.w("//line ", p.File, ":", strconv.Itoa(p.Line))
}

func (g *gen) next() string {
	g.tmp++
	return strconv.Itoa(g.tmp)
}

// ---- Names ----

func canon(name string) string { return strings.ToUpper(name) }

// moduleName turns "billing.bas" into "billing".
func moduleName(file string) string {
	file = strings.ReplaceAll(file, `\`, "/")
	if i := strings.LastIndex(file, "/"); i >= 0 {
		file = file[i+1:]
	}
	file = strings.TrimSuffix(strings.TrimSuffix(file, ".bas"), ".BAS")
	if file == "" {
		file = "main"
	}
	return sanitize(strings.ToLower(file))
}

// mangle builds b_<module>_<name> (design §4.3).
func (g *gen) mangle(name string) string {
	return "b_" + g.mod + "_" + sanitize(strings.ToLower(name))
}

// sanitize keeps [a-z0-9_] and escapes everything else, so distinct names stay distinct.
func sanitize(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '_':
			b.WriteRune(r)
		default:
			fmt.Fprintf(&b, "_x%x_", r)
		}
	}
	return b.String()
}

// goFileName avoids names that Go would treat as build-constrained
// (m_windows.go, m_x_test.go, …).
func goFileName(mod string) string {
	parts := strings.Split(mod, "_")
	last := parts[len(parts)-1]
	if constrainedSuffix[last] {
		return "m_" + mod + "_bas.go"
	}
	return "m_" + mod + ".go"
}

var constrainedSuffix = func() map[string]bool {
	m := map[string]bool{"test": true}
	for _, s := range strings.Fields(`aix android darwin dragonfly freebsd hurd illumos ios js linux
		nacl netbsd openbsd plan9 solaris wasip1 windows zos 386 amd64 amd64p32 arm armbe arm64
		arm64be loong64 mips mipsle mips64 mips64le mips64p32 mips64p32le ppc ppc64 ppc64le riscv
		riscv64 s390 s390x sparc sparc64 wasm`) {
		m[s] = true
	}
	return m
}()

// ---- Types ----

// typ is the static type of a generated Go expression.
type typ int

const (
	tAny  typ = iota // rt.Value
	tInt             // int64
	tNum             // float64
	tStr             // string
	tBool            // bool
	tDec             // rt.Decimal; its arithmetic and comparisons go through the rt helpers
)

func (t typ) goType() string {
	switch t {
	case tInt:
		return "int64"
	case tNum:
		return "float64"
	case tStr:
		return "string"
	case tBool:
		return "bool"
	case tDec:
		return "rt.Decimal"
	}
	return "rt.Value"
}

func (t typ) numeric() bool { return t == tInt || t == tNum }

func (t typ) zero() string {
	switch t {
	case tInt, tNum:
		return "0"
	case tStr:
		return `""`
	case tBool:
		return "false"
	case tDec:
		return "rt.Decimal{}"
	}
	return "nil"
}

// typeRef maps a declared type to its Go representation (Requirement 3.3).
func (g *gen) typeRef(p token.Pos, ref ast.TypeRef) (typ, string) {
	name := canon(ref.Name)
	switch name {
	case "INTEGER":
		return tInt, name
	case "NUMBER":
		return tNum, name
	case "STRING":
		return tStr, name
	case "BOOLEAN":
		return tBool, name
	case "", "ANY", "MAP", "ARRAY", "DATE", "NIL":
		return tAny, name
	case "DECIMAL":
		return tDec, name
	}
	g.errorf(p, diag.Undefined, "there is no type named %s; use NUMBER, INTEGER, STRING, BOOLEAN, MAP, ARRAY, DECIMAL, DATE, NIL or ANY", ref.Name)
	return tAny, name
}

// zeroFor is the value of a DIM without "= value".
func zeroFor(v *varInfo) string {
	return zeroForDecl(v.t, v.decl)
}

func zeroForDecl(t typ, decl string) string {
	switch decl {
	case "MAP":
		return "rt.NewMap()"
	case "ARRAY":
		return "rt.ArrayOf()"
	}
	return t.zero()
}
