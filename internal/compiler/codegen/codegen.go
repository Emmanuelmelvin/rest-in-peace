// Package codegen turns a checked program into Go source for package main
// (design §4). The output imports the runtime as "ripapp/rt".
package codegen

import (
	"github.com/rip-basic/rip/internal/compiler/ast"
	"github.com/rip-basic/rip/internal/compiler/diag"
	"github.com/rip-basic/rip/internal/compiler/token"
)

// RuntimeImport is the import path of the runtime inside a build directory.
const RuntimeImport = "ripapp/rt"

// Options control code generation.
type Options struct {
	// Guard inserts c.Guard() at loop back-edges and GOTOs (playground builds, design §4.12).
	Guard bool
}

// File is one generated Go file.
type File struct {
	Name string // e.g. "main.go", "m_billing.go"
	Src  []byte
}

// Generate emits Go source for the program.
func Generate(p *ast.Program, opts Options) ([]File, diag.List) {
	// TODO(task 1.5): structured mode.
	//   - Header: "// Code generated by rip. DO NOT EDIT."
	//   - A //line file.bas:N directive before every statement (design §4.5).
	//   - Mangle names: b_<module>_<name> in lowercase (design §4.3).
	//   - Every function takes c *rt.Ctx first and starts with: defer c.Enter()()
	//   - Typed declarations use native Go types; dynamic values use rt helpers.
	//   - main.go runs top-level statements in import order, then app.Run().
	// TODO(task 1.7): classic mode with labels and native goto (design §4.7).
	entry := ""
	if p != nil {
		entry = p.Entry
	}
	return nil, diag.List{diag.Todo(token.Pos{File: entry, Line: 1, Col: 1}, "1.5", "Go code generation")}
}
